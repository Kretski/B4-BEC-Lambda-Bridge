# HeavyScalar_TwoField: operator-level test (T1/T7) of Lorentz-invariant effective quartic vs B4 local polynomial.
import numpy as np, sympy as sp
from scipy.optimize import least_squares
P=np.polynomial.polynomial
# --- effective Lorentz-invariant Lagrangian L=1/2 X_phi + 1/2 X_psi + O^2/(2M^2), M=1, O = a (dphi)^2 + b (dpsi)^2 + e dphi.dpsi
ft,fx,gt,gx,a,b,e=sp.symbols('ft fx gt gx a b e',real=True)
Xp=ft**2-fx**2; Xs=gt**2-gx**2; Y=ft*gt-fx*gx
Leff=sp.Rational(1,2)*Xp+sp.Rational(1,2)*Xs+(a*Xp+b*Xs+e*Y)**2/2
jets=[ft,fx,gt,gx]; Hm=sp.hessian(Leff,jets); Hf=sp.lambdify((ft,fx,gt,gx,a,b,e),Hm,'numpy')
def poly_LI(bg,th):
    w,q,v,r=bg; H=np.array(Hf(w,q,v,r,*th),dtype=float)   # order (phi_t,phi_x,psi_t,psi_x)
    # K_ij(c) = sum H^{ij}_{ab} z_a z_b with z=(c,-1) (omega=c k, k=1; real form) ; det via sampling & fit deg 4
    def K(cc):
        z=np.array([cc,-1.0]); K=np.zeros((2,2))
        for i in range(2):
            for j in range(2):
                blk=H[2*i:2*i+2,2*j:2*j+2]; K[i,j]=z@blk@z
        return K
    cs=np.linspace(-2,2,15); d=np.array([np.linalg.det(K(c)) for c in cs])
    co=np.polyfit(cs,d,4)[::-1]; return co/co[-1]
def poly_B4(bg,th):
    w,q,v,r=bg; p,s,kap,Lam=th
    ap=p*w*q-kap*v*r; aps=-kap*w*q+s*v*r
    d1=np.array([-(1+3*Lam*q*q),-2*ap,1.]); d2=np.array([-1.,-2*aps,1.])
    F=P.polyadd(P.polyadd(P.polymul(d1,d2),p*P.polymul(P.polymul([w,-q],[w,-q]),d2)),s*P.polymul(P.polymul([v,-r],[v,-r]),d1))
    return F/F[-1]
rng=np.random.default_rng(3); bgs=[tuple(rng.uniform(-0.6,0.6,4)) for _ in range(15)]
def res(x,mode):
    out=[]
    for bg in bgs:
        t=poly_LI(bg,x[:3]) if mode=='LI' else poly_B4(bg,x[:4]) 
        out.append(t)
    return out
def fit(target_fn,nB4=4):
    T=[target_fn(bg) for bg in bgs]
    best=None
    for s0 in range(60):
        x0=rng.normal(0,0.5,nB4)
        f=lambda x:np.concatenate([poly_B4(bg,x)[:4]-t[:4] for bg,t in zip(bgs,T)])
        try: sol=least_squares(f,x0)
        except Exception: continue
        if best is None or sol.cost<best.cost: best=sol
    return best
# control: B4 polynomial generated by known constants should be recovered with ~0 residual
ctrl=fit(lambda bg:poly_B4(bg,(0.05,0.04,0.0447,0.3))); print("control B4->B4 residual (rms coeff):",np.sqrt(2*ctrl.cost/(15*4)))
# test: Lorentz-invariant two-field (several coupling choices) -> best-fit B4 constants
for th in [(0.2,0.2,0.0),(0.3,-0.2,0.1),(0.2,0.1,0.4),(0.5,0.5,0.0)]:
    sol=fit(lambda bg:poly_LI(bg,th)); 
    rms=np.sqrt(2*sol.cost/(15*4)); scale=np.sqrt(np.mean([np.sum((poly_LI(bg,th)[:4]-np.array([-1,0,0,0]*1))**2) for bg in bgs]))
    print("LI couplings",th,"-> best-fit B4 rms residual %.2e  (deviation of LI poly from free: %.2e)  fitted (p,s,k,L)=%s"%(rms,scale,np.round(sol.x,3)))
print("--- relative residual (residual / deviation of LI poly from free (c^2-1)^2), same fit ---")
free=np.array([1,0,-2,0,1.])[::-1]  # coefficients low->high of c^4-2c^2+1 : [1,0,-2,0,1]
free=np.array([1.,0.,-2.,0.,1.])
for th in [(0.2,0.2,0.0),(0.3,-0.2,0.1),(0.2,0.1,0.4),(0.5,0.5,0.0)]:
    T=[poly_LI(bg,th) for bg in bgs]; dev=np.sqrt(np.mean([np.sum((t[:4]-free[:4])**2) for t in T]))
    sol=fit(lambda bg:poly_LI(bg,th)); rms=np.sqrt(2*sol.cost/(15))
    print(th,"rms residual %.3e, deviation %.3e, ratio %.2f, kappa^2/(ps) fitted = %.2f"%(rms,dev,rms/dev,sol.x[2]**2/(sol.x[0]*sol.x[1])))
